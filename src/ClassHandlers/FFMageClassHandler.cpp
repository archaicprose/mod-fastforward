void FFMageClassHandler::LearnWeaponSkills(Player* p)
{
    p->learnSpell(WANDS);
    p->learnSpell(STAVES);
    p->learnSpell(SHOOT);
    p->learnSpell(ONE_H_SWORDS);
    p->learnSpell(DAGGERS);
}

void FFMageClassHandler::LearnSkills(Player* p)
{
    FFClassHandler::LearnSkills(p);
    FFClassHandler::LearnForLevel(p, FF_MAGE_SPELLS);

    // FIXME - this is inefficient
    if (p->GetTeamId() == TEAM_ALLIANCE) {
        FFClassHandler::LearnForLevel(p, FF_MAGE_PORTALS_A);
    }
    else {
        FFClassHandler::LearnForLevel(p, FF_MAGE_PORTALS_H);
    }
}

